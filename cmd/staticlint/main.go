func main() {
	multichecker.Main(analyzers()...)
}

func analyzers() []*analysis.Analyzer {

	checks := []*analysis.Analyzer{

		// Стандартные анализаторы Go:

		asmdecl.Analyzer,
		assign.Analyzer,
		atomic.Analyzer,
		bools.Analyzer,
		buildtag.Analyzer,
		cgocall.Analyzer,
		composite.Analyzer,
		copylock.Analyzer,
		defers.Analyzer,
		directive.Analyzer,
		errorsas.Analyzer,
		framepointer.Analyzer,
		httpresponse.Analyzer,
		ifaceassert.Analyzer,
		loopclosure.Analyzer,
		lostcancel.Analyzer,
		nilfunc.Analyzer,
		printf.Analyzer,
		shift.Analyzer,
		sigchanyzer.Analyzer,
		slog.Analyzer,
		stdmethods.Analyzer,
		stringintconv.Analyzer,
		structtag.Analyzer,
		testinggoroutine.Analyzer,
		tests.Analyzer,
		timeformat.Analyzer,
		unmarshal.Analyzer,
		unreachable.Analyzer,
		unsafeptr.Analyzer,
		unusedresult.Analyzer,
		waitgroup.Analyzer,

		// Публичные сторонние анализаторы:

		bodyclose.Analyzer,
		nilerr.Analyzer,

		// Собственный анализатор проекта:

		noosexit.Analyzer,
	}

	// Все анализаторы класса SA из Staticcheck:

	for _, analyzer := range staticcheck.Analyzers {
		checks = append(checks, analyzer.Analyzer)
	}

	// Дополнительный класс S из Staticcheck:

	for _, analyzer := range simple.Analyzers {
		checks = append(checks, analyzer.Analyzer)
	}

	return checks
}
