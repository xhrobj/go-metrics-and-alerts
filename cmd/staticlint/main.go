func main() {
	multichecker.Main(analyzers()...)
}

func analyzers() []*analysis.Analyzer {

	// Создайте свой `multichecker`, состоящий из:

	checks := []*analysis.Analyzer{

		// - стандартных статических анализаторов пакета golang.org/x/tools/go/analysis/passes

		asmdecl.Analyzer,
		assign.Analyzer,
		atomic.Analyzer,
		bools.Analyzer,
		buildtag.Analyzer,
		cgocall.Analyzer,
		composite.Analyzer,
		copylock.Analyzer,
		defers.Analyzer,
		directive.Analyzer,
		errorsas.Analyzer,
		framepointer.Analyzer,
		httpresponse.Analyzer,
		ifaceassert.Analyzer,
		loopclosure.Analyzer,
		lostcancel.Analyzer,
		nilfunc.Analyzer,
		printf.Analyzer,
		shift.Analyzer,
		sigchanyzer.Analyzer,
		slog.Analyzer,
		stdmethods.Analyzer,
		stringintconv.Analyzer,
		structtag.Analyzer,
		testinggoroutine.Analyzer,
		tests.Analyzer,
		timeformat.Analyzer,
		unmarshal.Analyzer,
		unreachable.Analyzer,
		unsafeptr.Analyzer,
		unusedresult.Analyzer,
		waitgroup.Analyzer,

		// - двух или более любых публичных анализаторов на ваш выбор

		bodyclose.Analyzer,
		nilerr.Analyzer,

		// добавьте в `multichecker` собственный анализатор, запрещающий использовать прямой вызов `os.Exit` в функции `main` пакета `main`

		noosexit.Analyzer,
	}

	// - всех анализаторов класса `SA` пакета `staticcheck.io`

	for _, analyzer := range staticcheck.Analyzers {
		checks = append(checks, analyzer.Analyzer)
	}

	// - не менее одного анализатора остальных классов пакета `staticcheck.io`

	for _, analyzer := range simple.Analyzers {
		checks = append(checks, analyzer.Analyzer)
	}

	return checks
}
