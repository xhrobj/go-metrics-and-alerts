/*
Package main implements staticlint - собственную CLI-утилиту статического анализа проекта.

Запуск:

	go run ./cmd/staticlint ./...

В проекте также доступна Makefile-цель:

	make staticlint

staticlint собран на базе multichecker. Multichecker получает список
analysis.Analyzer и запускает их над переданными Go-пакетами. При запуске
с аргументом ./... анализируются все обычные пакеты проекта; служебные
директории Go tooling, например testdata, в такой обход не попадают.

Отдельно собственный анализатор noosexit пропускает сгенерированные Go test
main-пакеты, чей import path заканчивается на .test. Такие пакеты создаются
инструментами Go для запуска тестов и могут содержать служебный os.Exit,
который не относится к пользовательскому коду проекта.

Состав multichecker:

1. Стандартные анализаторы Go из golang.org/x/tools/go/analysis/passes:

  - asmdecl - проверяет соответствие Go-объявлений и asm-реализаций.
  - assign - находит бесполезные самоприсваивания.
  - atomic - проверяет некорректное использование sync/atomic.
  - bools - находит подозрительные булевы выражения.
  - buildtag - проверяет корректность build tags.
  - cgocall - находит некорректные вызовы cgo.
  - composite - проверяет неименованные поля в composite literals.
  - copylock - находит копирование значений, содержащих lock.
  - defers - находит некорректные defer-вызовы.
  - directive - проверяет директивы компилятора.
  - errorsas - проверяет корректность errors.As.
  - framepointer - проверяет assembly-код на сохранение frame pointer.
  - httpresponse - находит ошибки обработки HTTP response.
  - ifaceassert - находит невозможные type assertion между интерфейсами.
  - loopclosure - находит захват переменных цикла в замыканиях.
  - lostcancel - находит потерянные cancel-функции context.
  - nilfunc - находит бесполезные сравнения функций с nil.
  - printf - проверяет форматные строки Printf-подобных функций.
  - shift - проверяет подозрительные операции сдвига.
  - sigchanyzer - находит ошибки при работе с signal.Notify.
  - slog - проверяет корректность вызовов log/slog.
  - stdmethods - проверяет сигнатуры стандартных методов.
  - stringintconv - находит подозрительные преобразования int в string.
  - structtag - проверяет корректность struct tags.
  - testinggoroutine - находит некорректное использование testing.T в горутинах.
  - tests - проверяет распространённые ошибки в тестах.
  - timeformat - находит ошибочные layout-строки time.Format.
  - unmarshal - проверяет аргументы json/xml.Unmarshal.
  - unreachable - находит недостижимый код.
  - unsafeptr - проверяет некорректные преобразования unsafe.Pointer.
  - unusedresult - находит проигнорированные результаты важных функций.
  - waitgroup - проверяет некорректное использование sync.WaitGroup.

2. Анализаторы класса SA из Staticcheck.

Подключены все анализаторы из honnef.co/go/tools/staticcheck. Это основной
класс Staticcheck для поиска ошибок, подозрительного кода, некорректного
использования стандартной библиотеки и потенциальных runtime-проблем.

3. Дополнительный класс анализаторов Staticcheck.

Подключены анализаторы класса S из honnef.co/go/tools/simple. Они находят
избыточный код и предлагают более простые эквивалентные конструкции.

4. Публичные сторонние анализаторы:

  - bodyclose - проверяет, что HTTP response body закрывается после использования.
  - nilerr - находит подозрительный возврат nil в ветках обработки ненулевой ошибки.

5. Собственный анализатор проекта:

  - noosexit - запрещает прямой вызов os.Exit внутри функции main пакета main.
    Анализатор проверяет только пользовательские main-пакеты и пропускает
    сгенерированные Go test main-пакеты.
*/
